    /// <summary>
    /// An array of small tagged-property structs — a curve — read element by element rather than by
    /// a fixed stride: each element's own terminator reports where it ends, the same way the
    /// top-level property list does. Returns null unless the compact count and every element consume
    /// the array's complete value, so a curve whose shape doesn't match what's expected here yields
    /// nothing rather than a partial or misaligned read.
    /// </summary>
    /// <summary>Reads an <c>Array</c>-of-struct property's elements as their own field lists.
    /// Shared beyond this class by <see cref="Assets.WeaponEffects"/> for the same reason the
    /// curve readers below need it: a struct array is a struct array regardless of what property
    /// holds it.</summary>
    internal static IReadOnlyList<List<UnrealProperty>>? ReadStructArrayElements(
        BioShockPackage package, UnrealProperty property)
    {
        int offset = 0;
        int count;
        try { count = PropertyValues.ReadCompactIndex(property.Value, ref offset); }
        catch (Exception ex) when (ex is InvalidDataException or IndexOutOfRangeException
                                       or ArgumentOutOfRangeException)
        {
            return null;
        }
        if (count < 0) return null;

        var elements = new List<List<UnrealProperty>>(count);
        for (int i = 0; i < count; i++)
        {
            List<UnrealProperty> fields;
            bool truncated;
            try
            {
                fields = UnrealPropertyReader.Read(property.Value, package.Names, out int end, out truncated, start: offset);
                offset = end;
            }
            catch (Exception ex) when (ex is InvalidDataException or IndexOutOfRangeException
                                           or ArgumentOutOfRangeException)
            {
                return null;
            }
            if (truncated) return null;
            elements.Add(fields);
        }

        return offset == property.Value.Length ? elements : null;
    }

    private static IReadOnlyList<FloatCurveKey>? ReadFloatCurve(
        BioShockPackage package, UnrealProperty property, string valueField)
    {
        if (ReadStructArrayElements(package, property) is not { } elements) return null;

        var result = new List<FloatCurveKey>(elements.Count);
        foreach (var fields in elements)
        {
            var time = fields.FirstOrDefault(f => f.Name == "RelativeTime" && f.Type == UnrealPropertyType.Float);
            var value = fields.FirstOrDefault(f => f.Name == valueField && f.Type == UnrealPropertyType.Float);
            if (time is null || value is null) return null;
            result.Add(new FloatCurveKey(time.AsFloat(), value.AsFloat()));
        }
        return result;
    }

    private static IReadOnlyList<ColorCurveKey>? ReadColorCurve(BioShockPackage package, UnrealProperty property)
    {
        if (ReadStructArrayElements(package, property) is not { } elements) return null;

        var result = new List<ColorCurveKey>(elements.Count);
        foreach (var fields in elements)
        {
            var time = fields.FirstOrDefault(f => f.Name == "RelativeTime" && f.Type == UnrealPropertyType.Float);
            var color = fields.FirstOrDefault(f => f.Name == "Color" && f.Type == UnrealPropertyType.Struct);
            if (time is null || color is null || PropertyValues.AsColor(color) is not { } decoded) return null;
            result.Add(new ColorCurveKey(time.AsFloat(), decoded));
        }
        return result;
    }

    private static IReadOnlyList<VectorCurveKey>? ReadVectorCurve(
        BioShockPackage package, UnrealProperty property, string valueField)
    {
        if (ReadStructArrayElements(package, property) is not { } elements) return null;

        var result = new List<VectorCurveKey>(elements.Count);
        foreach (var fields in elements)
        {
            var time = fields.FirstOrDefault(f => f.Name == "RelativeTime" && f.Type == UnrealPropertyType.Float);
            var value = fields.FirstOrDefault(f => f.Name == valueField && f.Type == UnrealPropertyType.Struct);
            if (time is null || value is null || PropertyValues.AsVector(value) is not { } decoded) return null;
            result.Add(new VectorCurveKey(time.AsFloat(), decoded));
        }
        return result;
    }

    /// <summary>
    /// UE2's <c>Range</c> struct: a nested tagged list with two <c>Float</c> fields, <c>Min</c> and
    /// <c>Max</c>. Returns null rather than a partial range when either field is missing, the same
    /// contract <see cref="ReadRegion"/> uses for its own nested struct.
    /// </summary>
    private static FloatRange? ReadFloatRange(BioShockPackage package, UnrealProperty property)
    {
        List<UnrealProperty> fields;
        try { fields = UnrealPropertyReader.Read(property.Value, package.Names, out _, start: 0); }
        catch (Exception ex) when (ex is InvalidDataException or IndexOutOfRangeException
                                       or ArgumentOutOfRangeException)
        {
            return null;
        }

        var min = fields.FirstOrDefault(field => field.Name == "Min" && field.Type == UnrealPropertyType.Float);
        var max = fields.FirstOrDefault(field => field.Name == "Max" && field.Type == UnrealPropertyType.Float);
        return min is null || max is null ? null : new FloatRange(min.AsFloat(), max.AsFloat());
    }

    /// <summary>UE2's <c>RangeVector</c> struct: one <see cref="FloatRange"/> per axis, X/Y/Z.</summary>
    private static AxisRange? ReadAxisRange(BioShockPackage package, UnrealProperty property)
    {
        List<UnrealProperty> fields;
        try { fields = UnrealPropertyReader.Read(property.Value, package.Names, out _, start: 0); }
        catch (Exception ex) when (ex is InvalidDataException or IndexOutOfRangeException
                                       or ArgumentOutOfRangeException)
        {
            return null;
        }

        FloatRange? Axis(string name) =>
            fields.FirstOrDefault(field => field.Name == name && field.Type == UnrealPropertyType.Struct) is { } axisField
                ? ReadFloatRange(package, axisField)
                : null;

        var x = Axis("X");
        var y = Axis("Y");
        var z = Axis("Z");
        return x is null || y is null || z is null ? null : new AxisRange(x.Value, y.Value, z.Value);
    }

    /// <summary>
    /// Resolves one object reference, looking first at the actor and then at its class defaults.
    /// <paramref name="expectedClass"/> rejects a reference whose target is of another class, which
    /// is what stops a name-shaped match from standing in for an identity.
    /// </summary>
    private static AssetReference? Reference(
        BioShockPackage package, ClassDefaults defaults, ActorPayload payload, string property, string? expectedClass)
    {
        string origin = "actor";
        var found = payload.Find(property);
        if (found is null)
        {
            found = defaults.Lookup(payload.Export.ClassIndex, property);
            origin = "class defaults";
        }
        if (found is null) return null;

        var index = PropertyValues.AsReference(found);
        if (index is null || index.Value.IsNull) return null;

        return Describe(package, index.Value, origin, expectedClass);
    }

    /// <summary>Resolves a package reference (export or import) to what it names, without reading
    /// its payload. Shared beyond this class by <see cref="Assets.WeaponEffects"/>, which resolves
    /// a weapon class's own <c>Class</c>-typed properties (<c>EmitterClass</c>, <c>LightClass</c>)
    /// the identical way an actor's <c>Object</c>-typed properties resolve here.</summary>
    internal static AssetReference? Describe(
        BioShockPackage package, PackageIndex index, string origin, string? expectedClass)
    {
        string objectName;
        string className;
        SourceId? source = null;

        if (index.IsExport)
        {
            if (index.ExportIndex >= package.Exports.Count) return null;
            var target = package.Exports[index.ExportIndex];
            className = package.GetClassName(target);
            objectName = target.ObjectName;
            if (expectedClass is not null && className != expectedClass) return null;
            source = new SourceId(
                Path.GetFileNameWithoutExtension(package.FilePath), target.Index, className, target.ObjectName);
        }
        else if (index.IsImport)
        {
            if (index.ImportIndex >= package.Imports.Count) return null;
            var import = package.Imports[index.ImportIndex];
            className = import.ClassName;
            objectName = import.ObjectName;
            if (expectedClass is not null && className != expectedClass) return null;
        }
        else return null;

        return new AssetReference
        {
            Index = index,
            ObjectName = objectName,
            ClassName = className,
            Origin = origin,
            Source = source,
        };
    }

    private static IReadOnlyList<AssetReference> ReferenceArray(
        BioShockPackage package, ActorPayload payload, string property)
    {
        if (payload.Find(property) is not { } found) return [];
        var result = new List<AssetReference>();
        foreach (var index in PropertyValues.AsReferenceArray(found))
        {
            if (Describe(package, index, "actor", null) is { } reference) result.Add(reference);
        }
        return result;
    }

    private static LevelContext Summarise(
        BioShockPackage package, string packageName, List<LevelActor> actors, List<SourceId> failed,
        Dictionary<string, int> uninterpreted)
    {
        var staticUsage = new Dictionary<SourceId, List<int>>();
        var skeletalUsage = new Dictionary<SourceId, List<int>>();
        var external = new List<AssetReference>();
        var unresolved = new List<AssetReference>();
        var withoutGeometry = new Dictionary<string, int>(StringComparer.Ordinal);

        for (int i = 0; i < actors.Count; i++)
        {
            var actor = actors[i];

            Record(actor.StaticMesh, staticUsage, i);
            Record(actor.SkeletalMesh, skeletalUsage, i);

            foreach (var reference in Enumerate(actor))
            {
                if (reference.Status == ResolutionStatus.External) external.Add(reference);
                else if (reference.Status == ResolutionStatus.Failed) unresolved.Add(reference);
            }

            if (!actor.HasGeometry)
                withoutGeometry[actor.Source.ClassName] = withoutGeometry.GetValueOrDefault(actor.Source.ClassName) + 1;
        }

        return new LevelContext
        {
            PackageFile = package.FilePath,
            PackageName = packageName,
            ExportCount = package.Exports.Count,
            ImportCount = package.Imports.Count,
            NameCount = package.Names.Count,
            Actors = actors,
            FailedActors = failed,
            StaticMeshUsage = staticUsage,
            SkeletalMeshUsage = skeletalUsage,
            ExternalReferences = external,
            UnresolvedReferences = unresolved,
            ClassesWithoutGeometry = withoutGeometry,
            UninterpretedProperties = uninterpreted,
        };

        static void Record(AssetReference? reference, Dictionary<SourceId, List<int>> usage, int actorIndex)
        {
            if (reference?.Source is not { } source) return;
            if (!usage.TryGetValue(source, out var users)) usage[source] = users = [];
            users.Add(actorIndex);
        }

        static IEnumerable<AssetReference> Enumerate(LevelActor actor)
        {
            if (actor.StaticMesh is not null) yield return actor.StaticMesh;
            if (actor.SkeletalMesh is not null) yield return actor.SkeletalMesh;
            if (actor.Brush is not null) yield return actor.Brush;
            foreach (var skin in actor.MaterialOverrides) yield return skin;
        }
    }

    /// <summary>
    /// The bounding box of every actor that has a position. Cheap sanity check on a level: Medical
    /// Pavilion should be tens of thousands of centimetres across, not millions.
    /// </summary>
    public static (Vector3 Min, Vector3 Max) Bounds(IEnumerable<LevelActor> actors)
    {
        var min = new Vector3(float.MaxValue);
        var max = new Vector3(float.MinValue);
        bool any = false;

        foreach (var actor in actors)
        {
            if (!actor.Transform.Present.Contains("Location")) continue;
            min = Vector3.Min(min, actor.Transform.Location);
            max = Vector3.Max(max, actor.Transform.Location);
            any = true;
        }

        return any ? (min, max) : (Vector3.Zero, Vector3.Zero);
    }
