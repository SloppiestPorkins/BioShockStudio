    public static LevelContext Analyze(string packageFile, IProgress<string>? progress = null)
    {
        using var package = BioShockPackage.Open(packageFile);
        return Analyze(package, progress);
    }

    public static LevelContext Analyze(BioShockPackage package, IProgress<string>? progress = null)
    {
        var defaults = new ClassDefaults(package);
        var actors = new List<LevelActor>();
        var failed = new List<SourceId>();
        var uninterpreted = new Dictionary<string, int>(StringComparer.Ordinal);
        string packageName = Path.GetFileNameWithoutExtension(package.FilePath);

        for (int i = 0; i < package.Exports.Count; i++)
        {
            var export = package.Exports[i];
            if (export.SerialSize < 64) continue;

            byte[] data;
            try { data = package.ReadExportData(export); }
            catch { continue; }

            var payload = ActorPayloadReader.TryRead(package, export, data);
            if (payload is null) continue;

            var source = new SourceId(packageName, export.Index, payload.ClassName, export.ObjectName);
            if (payload.Truncated)
            {
                failed.Add(source);
                continue;
            }

            actors.Add(BuildActor(package, defaults, source, payload, uninterpreted));

            if (progress is not null && actors.Count % 1000 == 0)
                progress.Report($"{actors.Count} actors");
        }

        ResolveMoverTriggers(actors);

        return Summarise(package, packageName, actors, failed, uninterpreted);
    }

    /// <summary>
    /// Second pass over the whole package: resolves every mover's <c>TriggeredBy</c> names against
    /// every other actor's <c>Label</c>, in place. Has to run after every actor in the package is
    /// built, unlike every other field on <see cref="LevelActor"/>, which is decoded from that one
    /// actor's own bytes — this is the one piece of "interaction metadata" that needs the whole
    /// package's Labels to resolve at all. See docs/research/interaction.md §2 for why <c>Label</c>
    /// and not <c>Tag</c>, and why an ambiguous name is left unresolved rather than guessed at.
    /// </summary>
    private static void ResolveMoverTriggers(List<LevelActor> actors)
    {
        var byLabel = new Dictionary<string, LevelActor>(StringComparer.Ordinal);
        var ambiguous = new HashSet<string>(StringComparer.Ordinal);
        foreach (var actor in actors)
        {
            if (actor.Label is not { } label) continue;
            if (!byLabel.TryAdd(label, actor)) ambiguous.Add(label);
        }

        for (int i = 0; i < actors.Count; i++)
        {
            var actor = actors[i];
            if (actor.Mover?.TriggeredBy is not { } raw
                || raw.Equals("none", StringComparison.OrdinalIgnoreCase))
                continue;

            var targets = new List<MoverTriggerTarget>();
            foreach (string rawName in raw.Split(','))
            {
                string name = rawName.Trim();
                if (name.Length == 0) continue;

                if (!ambiguous.Contains(name) && byLabel.TryGetValue(name, out var target))
                {
                    targets.Add(new MoverTriggerTarget
                    {
                        Name = name,
                        Resolved = true,
                        TargetExportIndex = target.Source.ExportIndex,
                        TargetClassName = target.Source.ClassName,
                    });
                }
                else
                {
                    targets.Add(new MoverTriggerTarget { Name = name, Resolved = false });
                }
            }

            actors[i] = actor with { Mover = actor.Mover with { ResolvedTriggers = targets } };
        }
    }

    /// <summary>
    /// Reads <c>Region</c>, UE2's <c>FPointRegion</c>, as a nested tagged property list.
    /// </summary>
    /// <remarks>
    /// Every actor in the game carries one. Returns null rather than a partial region when the
    /// nested walk fails, so a caller cannot mistake a parse failure for zone 0.
    /// </remarks>
    private static ActorRegion? ReadRegion(BioShockPackage package, ActorPayload payload)
    {
        if (payload.Find("Region") is not { Value.Length: > 0 } region) return null;

        List<UnrealProperty> fields;
        try { fields = UnrealPropertyReader.Read(region.Value, package.Names, out _); }
        catch (Exception ex) when (ex is InvalidDataException or IndexOutOfRangeException
                                       or ArgumentOutOfRangeException)
        {
            return null;
        }

        var leaf = fields.FirstOrDefault(f => f.Name == "iLeaf");
        var zone = fields.FirstOrDefault(f => f.Name == "ZoneNumber");
        if (leaf is null || zone is null) return null;

        return new ActorRegion { Leaf = leaf.AsInt(), ZoneNumber = zone.AsByte() };
    }

    private static LevelActor BuildActor(
        BioShockPackage package, ClassDefaults defaults, SourceId source, ActorPayload payload,
        Dictionary<string, int> uninterpreted)
    {
        foreach (var property in payload.Properties)
            if (!Interpreted.Contains(property.Name))
                uninterpreted[property.Name] = uninterpreted.GetValueOrDefault(property.Name) + 1;

        return new LevelActor
        {
            Source = source,
            Label = ReadName(package, payload, "Label"),
            Tag = ReadName(package, payload, "Tag"),
            Region = ReadRegion(package, payload),
            RegionActor = RegionActor(package, source.ClassName, payload),
            TrainingConcepts = NameArray(package, payload, "Concepts"),
            Spawner = Spawner(package, source.ClassName, payload),
            Cubemap = Reference(package, defaults, payload, "Cubemap", "Cubemap"),
            Projector = Projector(package, defaults, source.ClassName, payload),
            HavokForce = HavokForce(package, defaults, source.ClassName, payload),
            LootSlot = Reference(package, defaults, payload, "LootSlot", null),
            HavokConstraint = HavokConstraint(package, defaults, source.ClassName, payload),
            AntiPortal = Reference(package, defaults, payload, "AntiPortal", null),
            MapUiMarker = MapUiMarker(package, source.ClassName, payload),
            Vending = Vending(package, defaults, source.ClassName, payload),
            Interaction = Interaction(package, source.ClassName, payload),
            LevelInfo = LevelInfo(package, defaults, source.ClassName, payload),
            ShockAiScout = ShockAiScout(package, defaults, source.ClassName, payload),
            Mover = Mover(package, source.ClassName, payload),
            Door = Door(package, defaults, payload),
            DoorSwitch = DoorSwitch(package, defaults, source.ClassName, payload),
            Transform = ReadTransform(payload),
            StaticMesh = Reference(package, defaults, payload, "StaticMesh", "StaticMesh"),
            SkeletalMesh = Reference(package, defaults, payload, "Mesh", "SkeletalMesh")
                           ?? Reference(package, defaults, payload, "SkeletalMesh", "SkeletalMesh"),
            Brush = Reference(package, defaults, payload, "Brush", "Model"),
            Attachment = Reference(package, defaults, payload, "Base", null)
                         ?? Reference(package, defaults, payload, "Owner", null),
            Navigation = Navigation(package, payload),
            ScriptActions = ScriptActions(package, payload),
            Emitters = Emitters(package, payload),
            MaterialOverrides = ReferenceArray(package, payload, "Skins"),
            Groups = ReferenceArray(package, payload, "OwnerGroups").Select(r => r.ObjectName).ToList(),
            Properties = payload.Properties,
            Truncated = payload.Truncated,
            Trailer = payload.Trailer,
            UnknownHeaderField = payload.UnknownHeaderField,
        };
    }

    /// <summary>
    /// Reads the transform properties. Each is optional and each absence means the engine default,
    /// so which ones were present is recorded rather than inferred back from the values.
    /// </summary>
    public static ActorTransform ReadTransform(ActorPayload payload)
    {
        var present = new List<string>();
        var transform = ActorTransform.Default;

        if (payload.Find("Location") is { } location && PropertyValues.AsVector(location) is { } l)
        {
            transform = transform with { Location = l };
            present.Add("Location");
        }
        if (payload.Find("Rotation") is { } rotation && PropertyValues.AsRotator(rotation) is { } r)
        {
            transform = transform with { Rotation = r };
            present.Add("Rotation");
        }
        if (payload.Find("DrawScale") is { } drawScale && drawScale.Value.Length >= 4)
        {
            transform = transform with { DrawScale = drawScale.AsFloat() };
            present.Add("DrawScale");
        }
        if (payload.Find("DrawScale3D") is { } drawScale3D && PropertyValues.AsVector(drawScale3D) is { } s)
        {
            transform = transform with { DrawScale3D = s };
            present.Add("DrawScale3D");
        }
        if (payload.Find("PrePivot") is { } prePivot && PropertyValues.AsVector(prePivot) is { } p)
        {
            transform = transform with { PrePivot = p };
            present.Add("PrePivot");
        }

        return transform with { Present = present };
    }

    private static string? ReadName(BioShockPackage package, ActorPayload payload, string property) =>
        payload.Find(property) is { } found ? PropertyValues.AsName(found, package) : null;

    private static IReadOnlyList<string> NameArray(BioShockPackage package, ActorPayload payload, string property) =>
        payload.Find(property) is { Type: UnrealPropertyType.Array } found
        && PropertyValues.TryAsNameIndexArrayExact(found, package, out var values) ? values : [];

    private static SpawnerActorData? Spawner(BioShockPackage package, string className, ActorPayload payload)
    {
        if (!className.EndsWith("Spawner", StringComparison.Ordinal)) return null;
        string[] aiArrayNames = ["GlobalAITypes", "InitialAITypes", "RepopulationAITypes"];
        if (!aiArrayNames.Any(name => payload.Find(name) is not null)
            && payload.Find("OverriddenAIArchetypeNames") is null
            && payload.Find("SpawnZones") is null) return null;

        bool complete = true;
        IReadOnlyList<string> IndexNames(string name)
        {
            if (payload.Find(name) is not { Type: UnrealPropertyType.Array } property) return [];
            if (PropertyValues.TryAsNameIndexArrayExact(property, package, out var values)) return values;
            complete = false;
            return [];
        }
        IReadOnlyList<string> NumberedNames(string name)
        {
            if (payload.Find(name) is not { Type: UnrealPropertyType.Array } property) return [];
            if (PropertyValues.TryAsNameArrayExact(property, package, out var values)) return values;
            complete = false;
            return [];
        }

        return new SpawnerActorData
        {
            GlobalPatrol = ReadName(package, payload, "GlobalPatrol"),
            InitialPatrol = ReadName(package, payload, "InitialPatrol"),
            RepopulationPatrol = ReadName(package, payload, "RepopulationPatrol"),
            InitialLabel = ReadName(package, payload, "InitialLabel"),
            GlobalAiTypes = IndexNames("GlobalAITypes"),
            InitialAiTypes = IndexNames("InitialAITypes"),
            RepopulationAiTypes = IndexNames("RepopulationAITypes"),
            OverriddenAiArchetypeNames = NumberedNames("OverriddenAIArchetypeNames"),
            SpawnZones = NumberedNames("SpawnZones"),
            Complete = complete,
        };
    }

    private static ProjectorActorData? Projector(
        BioShockPackage package, ClassDefaults defaults, string className, ActorPayload payload)
    {
        if (className is not ("GoreLight_Decal" or "Caustic_Projector" or "Projector")) return null;
        bool complete = true;
        int? Int(string name) => payload.Find(name) is { Type: UnrealPropertyType.Int } value
            && value.Value.Length == 4 ? BinaryPrimitives.ReadInt32LittleEndian(value.Value) : null;
        float? Float(string name) => payload.Find(name) is { Type: UnrealPropertyType.Float } value
            && value.Value.Length == 4 ? BinaryPrimitives.ReadSingleLittleEndian(value.Value) : null;
        bool? Bool(string name) => payload.Find(name) is { Type: UnrealPropertyType.Bool } value
            ? value.BoolValue : null;
        Vector3? tile = payload.Find("Tile") is { Type: UnrealPropertyType.Struct, StructName: "Vector" } tileProperty
            ? PropertyValues.AsVector(tileProperty) : null;
        PropertyValues.ProjectorGradient? gradient = null;
        if (payload.Find("AngleGradient") is { Type: UnrealPropertyType.Struct, StructName: "ProjectorGradient" } angle)
        {
            if (PropertyValues.TryAsProjectorGradientExact(angle, package, out var decoded)) gradient = decoded;
            else complete = false;
        }
        return new ProjectorActorData
        {
            Material = Reference(package, defaults, payload, "Material", null),
            Tile = tile,
            MaxTraceDistance = Int("MaxTraceDistance"),
            ZBiasOverride = Int("ZBiasOverride"),
            ScaleInTime = Float("ScaleInTime"),
            AngleGradient = gradient,
            ProjectOnBackfaces = Bool("bProjectOnBackfaces"),
            ProjectStaticMesh = Bool("bProjectStaticMesh"),
            ProjectSkeletalMesh = Bool("bProjectSkeletalMesh"),
            ShouldBeAttached = Bool("bShouldBeAttached"),
            Complete = complete,
        };
    }

